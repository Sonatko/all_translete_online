# Pre-compiled regex for punctuation stripping and tokenization
_WORD_REGEX = re.compile(r"^[a-zA-Z]+$")
_TOKEN_SPLIT_REGEX = re.compile(r"([a-zA-Z]+|[^a-zA-Z\s]+|\s+)")

# Common suffixes for basic English lemmatization without external dependencies
_SUFFIXES = ("ing", "edly", "ingly", "ed", "es", "ly", "ment", "ness", "tion", "sion", "s", "able", "al")


def is_target_vocab_word(raw_word: str) -> bool:
    """Determine if an English word is a B2-C1 key vocabulary item in < 0.001ms.
    
    Performs fast hash lookup on normalized lemma and common morphological stems.
    """
    clean = raw_word.strip().lower()
    if not clean or len(clean) < 4:
        return False

    # 1. Direct hash lookup (O(1))
    if clean in _TARGET_VOCAB_LEMMAS:
        return True

    # 2. Fast morphological stemming for inflected forms (e.g. absent -> absently, complete -> completed)
    for suffix in _SUFFIXES:
        if clean.endswith(suffix):
            stem = clean[:-len(suffix)]
            if len(stem) >= 3:
                if stem in _TARGET_VOCAB_LEMMAS:
                    return True
                # e-dropping (e.g. accelerating -> accelerate)
                if (stem + "e") in _TARGET_VOCAB_LEMMAS:
                    return True
                # consonant doubling (e.g. stopped -> stop)
                if len(stem) > 2 and stem[-1] == stem[-2] and stem[:-1] in _TARGET_VOCAB_LEMMAS:
                    return True

    return False


def tokenize_with_vocab_flags(text: str) -> list:
    """Split text into (token_str, is_target_word) tuples for rich colored rendering.
    
    Guarantees that re-assembling token_str reproduces the exact original text.
    """
    if not text:
        return []

    tokens = _TOKEN_SPLIT_REGEX.findall(text)
    result = []
    for tok in tokens:
        if tok and tok[0].isalpha():
            result.append((tok, is_target_vocab_word(tok)))
        else:
            result.append((tok, False))
    return result
